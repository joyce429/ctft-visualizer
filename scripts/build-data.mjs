import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  signals: resolve(projectRoot, "data/signals.json"),
  references: resolve(projectRoot, "data/references.json"),
  properties: resolve(projectRoot, "data/transform-properties.json")
};

const [signals, references, properties] = await Promise.all(
  Object.values(files).map(async (path) => JSON.parse(await readFile(path, "utf8")))
);

const outputPath = resolve(projectRoot, "src/data/generated/signals.generated.js");
await mkdir(dirname(outputPath), { recursive: true });
const banner = "// Generated by scripts/build-data.mjs. Do not edit by hand.\n";
const moduleText = `${banner}export const SIGNAL_DATABASE = ${JSON.stringify(signals, null, 2)};\n\n` +
  `export const REFERENCE_DATABASE = ${JSON.stringify(references, null, 2)};\n\n` +
  `export const TRANSFORM_PROPERTIES = ${JSON.stringify(properties, null, 2)};\n`;
await writeFile(outputPath, moduleText, "utf8");
console.log(`Built offline data module: ${outputPath}`);
